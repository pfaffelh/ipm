// In the tactic mode: the introduction once, then each tactic's tip when it is first offered (exact
// in 1.1, constructor only at an ∧ goal); a solved level turns the board green and counts on the
// world map at once; the last level of a world leads to the next world; on boards of their own, a
// case done turns its board green. Usage: BASE=http://localhost:8002/ node progress.mjs (SHOT=dir)
import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? '/usr/bin/google-chrome', headless: true })
const base = process.env.BASE ?? 'http://127.0.0.1:8002/'
const page = await (await browser.newContext({ viewport: { width: 1300, height: 800 } })).newPage()
page.on('pageerror', e => console.log('PAGEERROR', e.message))
const tap = async l => { await l.dispatchEvent('click'); await page.waitForTimeout(200) }
const tip = async () => { const c = page.locator('.ipm-tip-card'); if (!(await c.count())) return '(none)'; const t = (await c.innerText()).replace(/\s+/g, ' ').slice(0, 110); await page.locator('.ipm-tip-ok').click(); return t }
await page.goto(base)
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('ipm-verso:mode', 'tactics') })
await page.goto(base + 'World-1___-Conjunction/#level-1'); await page.waitForTimeout(500)
console.log('1.1 at the start:', await tip())
const t = page.locator('.ipm-task.ipm-current')
await tap(t.locator('.ipm-conclusion .ipm-port.ipm-in'))
console.log('1.1 goal tapped:', await tip())
const count = () => page.locator('.ipm-map-world').first().locator('.ipm-map-count').textContent()
console.log('map before:', await count())
await tap(t.locator('.ipm-step', { hasText: 'exact' }))
await page.waitForTimeout(500)
console.log('solved:', await t.locator('.ipm-status').innerText(), '| board green:', await t.locator('.ipm-canvas.ipm-board-done').count(), '| map after:', await count())
if (process.env.SHOT) await page.screenshot({ path: process.env.SHOT + '/progress-solved.png' })
await page.goto(base + 'World-1___-Conjunction/#level-4'); await page.reload(); await page.waitForTimeout(500)
console.log('1.4 at the start:', await tip())
await tap(page.locator('.ipm-task.ipm-current .ipm-conclusion .ipm-port.ipm-in'))
console.log('1.4 goal A ∧ B tapped:', await tip())
await page.evaluate(() => localStorage.setItem('ipm-verso:in-order', 'off'))
await page.goto(base + 'World-1___-Conjunction/#level-13'); await page.reload(); await page.waitForTimeout(500)
await page.locator('.ipm-tip-ok').click().catch(() => {})
const next = page.locator('.ipm-task.ipm-current .ipm-next')
console.log('1.13 next:', (await next.innerText()).replace(/\s+/g, ' '), '| enabled:', await next.isEnabled())
await next.click(); await page.waitForTimeout(600)
console.log('  leads to:', new URL(page.url()).pathname)
// boards: case 1 done turns its board green
await page.goto(base + 'World-3___-Disjunction/#level-5'); await page.evaluate(() => localStorage.setItem('ipm-verso:in-order', 'off')); await page.reload(); await page.waitForTimeout(500)
for (let k = 0; k < 3; k++) await page.locator('.ipm-tip-ok').click({ timeout: 800 }).catch(() => {})
const u = page.locator('.ipm-task.ipm-current')
await tap(u.locator('.ipm-assumption .ipm-port.ipm-out').first()); await page.locator('.ipm-tip-ok').click({ timeout: 800 }).catch(() => {})
await tap(u.locator('.ipm-step', { hasText: 'obtain' }))
await tap(u.locator('.ipm-canvas .ipm-port.ipm-in.ipm-open').first()); await page.locator('.ipm-tip-ok').click({ timeout: 800 }).catch(() => {})
await tap(u.locator('.ipm-step', { hasText: 'right' }))
await tap(u.locator('.ipm-canvas .ipm-port.ipm-in.ipm-open').first()); await tap(u.locator('.ipm-step', { hasText: 'exact' }))
// now one board left (case 2); look at case 1 via its tab after both are done
await tap(u.locator('.ipm-canvas .ipm-port.ipm-in.ipm-open').first()); await tap(u.locator('.ipm-step', { hasText: 'left' }))
await tap(u.locator('.ipm-canvas .ipm-port.ipm-in.ipm-open').first()); await tap(u.locator('.ipm-step', { hasText: 'exact' }))
console.log('3.5 done: tabs', JSON.stringify(await u.locator('.ipm-board-tab').allTextContents()), '| green:', await u.locator('.ipm-canvas.ipm-board-done').count())
console.log('Lean:\n' + await u.locator('.ipm-lean-code').textContent())
await browser.close()
