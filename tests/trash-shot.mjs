// Screenshot while dragging a block towards the trash can (simulated phone).
import { chromium } from 'playwright-core'
import { allTasks } from './all-tasks.mjs'
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? '/usr/bin/google-chrome', headless: true })
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2 })
const page = await ctx.newPage()
await allTasks(page)
await page.goto((process.env.BASE ?? 'http://127.0.0.1:8002/') + 'World-2___-Implication/')
await page.evaluate(() => localStorage.clear()); await page.reload()
const t = page.locator('.ipm-task').nth(0)
await t.locator('.ipm-menu-item[title^="→E"]').dispatchEvent('click'); await page.waitForTimeout(200)
await t.locator('.ipm-board').scrollIntoViewIfNeeded()
const cdp = await ctx.newCDPSession(page)
const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y }] })
const r = await t.locator('.ipm-canvas .ipm-rule rect').boundingBox()
await touch('touchStart', r.x + r.width / 2, r.y + r.height / 2)
for (let k = 1; k <= 6; k++) await touch('touchMove', r.x + r.width / 2 + 10 * k, r.y + r.height / 2 + 15 * k)
await page.waitForTimeout(200)
const trash = await t.locator('.ipm-trash').boundingBox(), board = await t.locator('.ipm-canvas').boundingBox(), menu = await t.locator('.ipm-menu').boundingBox()
console.log(`board ${Math.round(board.y)}–${Math.round(board.y + board.height)}, menu top ${Math.round(menu.y)}, trash at y ${Math.round(trash.y)}–${Math.round(trash.y + trash.height)}, x ${Math.round(trash.x)}–${Math.round(trash.x + trash.width)} (board right ${Math.round(board.x + board.width)})`)
await page.screenshot({ path: process.env.SHOT ?? 'trash.png' })
await touch('touchEnd')
await browser.close()
