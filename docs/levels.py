# Writes docs/levels.md: every world and level, what it needs and gives, and checks the dependencies:
# - the rules a level's hidden Lean proof uses (roughly, by its words) are offered in its world,
# - every lemma comes before the levels that use it,
# - texts that point to another level ("level 6", "level 7 of the previous world") still fit.
# Usage (from the repository): python3 docs/levels.py   (exits with 1 if a check fails)
import re, sys
ORDER = ['Conjunction', 'Implication', 'Disjunction', 'Falsity', 'Classical', 'Iff', 'Rewriting', 'Quantifiers', 'Puzzles', 'Induction']
NEEDS = [  # word in the Lean proof → rule
    (r'⟨', 'conjI'), (r'\.[12]\b', 'conjE'), (r'\bfun\b', 'impI'), (r'\bOr\.inl\b', 'disjI1'), (r'\bOr\.inr\b', 'disjI2'),
    (r'\bClassical\.em\b', 'TND'), (r'\bIff\.intro\b', 'iffI'), (r'\.mp\b', 'iffE1'), (r'\.mpr\b', 'iffE2'), (r'\btrivial\b', 'trueI'),
    (r'\bNat\.rec\b', 'ind'), (r'\bbyContradiction\b', 'raa'),
    (r'^\s*rfl$', 'refl'), (r'^\s*symm$', 'symm'), (r'\brw \[[^←]', 'rw'), (r'\brw \[←', 'rwr'),
]
USES = {  # lemma (statement) → levels (statements) that it shortens, as they were chosen
    'A → B, B → C ⊢ A → C': ['A → ⊥, B → A ⊢ B → ⊥', 'A → B, B → C ⊢ (A → ⊥) ∨ C'],
    'A ∨ B ⊢ B ∨ A': [' ⊢ P ∨ Q ↔ Q ∨ P'],
    '(A → C) ∧ (B → C) ⊢ A ∨ B → C': ['(A → ⊥) ∧ (B → ⊥) ⊢ A ∨ B → ⊥'],
    'A ∨ B → C ⊢ (A → C) ∧ (B → C)': ['A ∨ B → ⊥ ⊢ (A → ⊥) ∧ (B → ⊥)'],
    'A ∨ B → ⊥ ⊢ (A → ⊥) ∧ (B → ⊥)': [' ⊢ (P ∨ Q → ⊥) ↔ (P → ⊥) ∧ (Q → ⊥)'],
    '(A → ⊥) ∧ (B → ⊥) ⊢ A ∨ B → ⊥': [' ⊢ (P ∨ Q → ⊥) ↔ (P → ⊥) ∧ (Q → ⊥)'],
    '(A → ⊥) ∨ (B → ⊥) ⊢ A ∧ B → ⊥': [' ⊢ (P ∧ Q → ⊥) ↔ (P → ⊥) ∨ (Q → ⊥)'],
    '(A → ⊥) ∨ B ⊢ A → B': [' ⊢ (P → Q) ↔ (P → ⊥) ∨ Q'],
    'A ∧ B → ⊥ ⊢ (A → ⊥) ∨ (B → ⊥)': [' ⊢ (P ∧ Q → ⊥) ↔ (P → ⊥) ∨ (Q → ⊥)', 'A ∧ B ∧ C → ⊥ ⊢ (A → ⊥) ∨ (B → ⊥) ∨ (C → ⊥)'],
    '(A → ⊥) → ⊥ ⊢ A': [' ⊢ ((P → ⊥) → ⊥) ↔ P', '(∀ x, P x) → ⊥ ⊢ ∃ x, P x → ⊥'],
    'A → B ⊢ (A → ⊥) ∨ B': [' ⊢ (P → Q) ↔ (P → ⊥) ∨ Q', 'A → B, B → C ⊢ (A → ⊥) ∨ C'],
    '(A → B) → ⊥ ⊢ A ∧ (B → ⊥)': [' ⊢ ((P → Q) → ⊥) ↔ P ∧ (Q → ⊥)'],
    'P ∧ Q ∨ P ∧ R ⊢ P ∧ (Q ∨ R)': [' ⊢ P ∧ (Q ∨ R) ↔ P ∧ Q ∨ P ∧ R'],
    '(P ∨ Q) ∧ (P ∨ R) ⊢ P ∨ Q ∧ R': [' ⊢ P ∨ Q ∧ R ↔ (P ∨ Q) ∧ (P ∨ R)'],
    '(∀ x, P x) → ⊥ ⊢ ∃ x, P x → ⊥': ['(∀ x, P x) → A ⊢ ∃ x, P x → A', ' ⊢ ∃ x, P x → ∀ y, P y'],
}
def attr(line, key):
    m = re.search(rf'\({key} := "([^"]*)"\)', line); return m.group(1) if m else ''
levels, problems, out = [], [], ['# Worlds and levels', '', 'Generated by `python3 docs/levels.py`, which also checks the dependencies.', '',
  'Columns: level, statement, rules its Lean proof uses (roughly), lemma (L) / tactic it unlocks / tip.', '']
for w, name in enumerate(ORDER, 1):
    s = open(f'Ipm/Sessions/{name}.lean').read()
    title = re.search(r'#doc \(Manual\) "([^"]*)"', s).group(1)
    out += [f'## {title}', '', '| | statement | rules used | gives |', '|---|---|---|---|']
    for k, m in enumerate(re.finditer(r'^::::task ([^\n]*)\n(.*?)\n::::\n', s, flags=re.M | re.S), 1):
        line, body = m.group(1), m.group(2)
        st = f"{attr(line, 'assumptions').replace(';', ',')} ⊢ {attr(line, 'conclusions')}"
        rules = [r.strip() for r in attr(line, 'rules').split(',') if r.strip()] or ['conjI', 'conjE', 'impI', 'impE']
        proof = re.search(r'```lean -show\n(.*?)```', body, re.S).group(1)
        need = sorted({r for pat, r in NEEDS if re.search(pat, proof)} | ({'falseE'} if re.search(r'(\)|\w)\.elim\b', proof) and ('⊥' in st or 'False' in proof) and re.search(r'False', proof) else set()))
        need = [r for r in need if not (r == 'falseE' and 'falseE' not in rules and not re.search(r'\(\w+ \w+\)\.elim|\b[a-z]\.elim\b(?! \()', proof))]
        missing = [r for r in need if r not in rules and not r.startswith('iffE') or (r.startswith('iffE') and r not in rules)]
        if missing: problems.append(f'{w}.{k} {st}: its proof uses {missing}, not offered in {title}')
        gives = ' '.join(x for x in ['L' if '(lemma := true)' in line else '', attr(line, 'unlocks'), 'tip' if ':::tip' in body else ''] if x)
        out.append(f'| {w}.{k} | `{st}` | {", ".join(need)} | {gives} |')
        levels.append((w, k, st, '(lemma := true)' in line, body))
    out.append('')
where = {st: (w, k) for w, k, st, _, _ in levels}
out += ['## Lemmas and where they help', '']
for lemma, users in USES.items():
    if lemma not in where: problems.append(f'lemma {lemma} not found'); continue
    lw = where[lemma]
    if not next(l for l in levels if (l[0], l[1]) == lw)[3]: problems.append(f'{lw[0]}.{lw[1]} {lemma} is not marked as a lemma')
    for u in users:
        if u not in where: problems.append(f'level {u} (uses {lemma}) not found'); continue
        if where[u] <= lw: problems.append(f'{where[u][0]}.{where[u][1]} uses lemma {lw[0]}.{lw[1]}, which comes after it')
    out.append(f'* {lw[0]}.{lw[1]} `{lemma}` → ' + ', '.join(f'{where[u][0]}.{where[u][1]}' for u in users if u in where))
# texts that point to other levels
for w, k, st, _, body in levels:
    for m in re.finditer(r'level (\d+) of the previous world', body):
        target = next((l for l in levels if (l[0], l[1]) == (w - 1, int(m.group(1)))), None)
        if not target or 'A → B ⊢ (B → ⊥) → A → ⊥' != target[2]: problems.append(f'{w}.{k}: "level {m.group(1)} of the previous world" is {target and target[2]}')
    for m in re.finditer(r'the other direction of level (\d+)', body):
        target = next((l for l in levels if (l[0], l[1]) == (w, int(m.group(1)))), None)
        if not target or target[2] != 'A ∨ B ∨ C ⊢ (A ∨ B) ∨ C': problems.append(f'{w}.{k}: "level {m.group(1)}" is {target and target[2]}')
    for m in re.finditer(r'Level (\d+), with three parts', body):
        target = next((l for l in levels if (l[0], l[1]) == (w, int(m.group(1)))), None)
        if not target or target[2] != 'A ∧ B → ⊥ ⊢ (A → ⊥) ∨ (B → ⊥)': problems.append(f'{w}.{k}: "Level {m.group(1)}" is {target and target[2]}')
# the number of levels of each world in the map of ipm.js
js = open('Ipm/ipm.js').read()
for w, name in enumerate(ORDER, 1):
    n = sum(1 for l in levels if l[0] == w)
    m = re.search(rf'n: {w}, levels: (\d+)', js)
    if not m or int(m.group(1)) != n: problems.append(f'world {w} has {n} levels, the map in ipm.js says {m and m.group(1)}')
out += ['', '## Checks', ''] + ([f'* ✗ {p}' for p in problems] or ['* ✓ all dependencies fit'])
open('docs/levels.md', 'w').write('\n'.join(out) + '\n')
print('\n'.join(problems) or 'all dependencies fit', f'({len(levels)} levels)')
sys.exit(1 if problems else 0)
